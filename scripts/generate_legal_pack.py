def markdown_to_docx(markdown: str, title: str, path: Path):
    doc = Document(); configure_doc(doc, title)
    lines = markdown.splitlines(); idx = 0
    while idx < len(lines):
        line = lines[idx].strip()
        if not line: idx += 1; continue
        if line == "<!-- PAGE BREAK -->":
            doc.add_page_break(); idx += 1; continue
        if line.startswith("|") and line.endswith("|"):
            rows = []
            while idx < len(lines) and lines[idx].strip().startswith("|"):
                rows.append([c.strip() for c in lines[idx].strip().strip("|").split("|")]); idx += 1
            if len(rows) >= 2:
                table = doc.add_table(rows=1, cols=len(rows[0])); table.alignment = WD_TABLE_ALIGNMENT.CENTER; table.style = "Table Grid"
                for i, cell_text in enumerate(rows[0]):
                    cell = table.rows[0].cells[i]; cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER; add_runs(cell.paragraphs[0], cell_text)
                    for run in cell.paragraphs[0].runs: run.bold = True
                    set_cell_margins(cell)
                for data in rows[2:]:
                    cells = table.add_row().cells
                    for i, cell_text in enumerate(data[:len(cells)]): add_runs(cells[i].paragraphs[0], cell_text); set_cell_margins(cells[i])
                for row in table.rows:
                    row._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
            continue
        if line.startswith("# "):
            p = doc.add_paragraph(style="Title"); add_runs(p, line[2:]); p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        elif line.startswith("## "):
            p = doc.add_paragraph(style="Heading 1"); add_runs(p, line[3:])
        elif line.startswith("> "):
            p = doc.add_paragraph(); p.paragraph_format.left_indent = Cm(0.45); p.paragraph_format.right_indent = Cm(0.2)
            p.paragraph_format.space_before = Pt(6); p.paragraph_format.space_after = Pt(8); add_runs(p, line[2:])
            p.runs[0].font.color.rgb = RGBColor(139, 85, 0)
        elif re.match(r"^\d+\. ", line):
            p = doc.add_paragraph(style="List Number"); add_runs(p, re.sub(r"^\d+\. ", "", line))
        elif line.startswith("- "):
            p = doc.add_paragraph(style="List Bullet"); add_runs(p, line[2:])
        else:
            p = doc.add_paragraph(); add_runs(p, line.replace("  ", " "))
        idx += 1
    doc.save(path)


