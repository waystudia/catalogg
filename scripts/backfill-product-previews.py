#!/usr/bin/env python3
"""Historical public product photo variants. Prepare locally (Pillow); apply on VPS.
Snapshot/plan are private operational artifacts. No files or rows are deleted.
"""
import argparse
import base64
import collections
import hashlib
import io
import json
import os
from pathlib import Path
import re
import subprocess
import time
import urllib.error
import urllib.parse
import urllib.request

PUBLIC = 'https://api.wayyaam.ru/storage/v1/object/public/catalog-assets/'
MAX_BYTES = 20 * 1024 * 1024


def has_preview(source):
    return bool(re.search(r'/catalog-assets/[^/]+/media/[a-f0-9]{64}\.full-v1\.(jpg|png|webp|avif)(?:\?|$)', source))


def legacy_id(snapshot):
    return next(row['id'] for row in snapshot['catalogs'] if row['slug'] == 'mangal')


def references(snapshot):
    result = collections.Counter()
    for row in snapshot['product_images']:
        if row['url']:
            result[(row['catalog_id'], row['url'])] += 1
    catalog_id = legacy_id(snapshot)
    for row in snapshot['product']:
        for source in [row.get('image_url')] + (row.get('image_urls') or []):
            if source:
                result[(catalog_id, source)] += 1
    return result


def source_url(source):
    if source.startswith('/catalogg/assets/'):
        source = source.removeprefix('/catalogg')
    if source.startswith('/assets/'):
        return urllib.parse.quote('https://wayyaam.ru' + source, safe=':/?&=%+#')
    parsed = urllib.parse.urlsplit(source)
    if parsed.scheme != 'https' or parsed.hostname not in {'api.wayyaam.ru', 'wayyaam.ru', 'images.unsplash.com'} or parsed.username or parsed.password or parsed.port not in (None, 443):
        raise ValueError('Unapproved public photo URL')
    if parsed.hostname == 'images.unsplash.com':
        return urllib.parse.quote('https://wayyaam.ru/media/unsplash' + parsed.path + ('?' + parsed.query if parsed.query else ''), safe=':/?&=%+#')
    return urllib.parse.quote(source, safe=':/?&=%+#')


class PublicRedirects(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        source_url(newurl)  # Never follow a stored photo URL into another/private host.
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def download(source):
    if source.startswith('data:image/'):
        match = re.fullmatch(r'data:image/(jpeg|png|webp|avif|gif);base64,(.*)', source, re.S)
        if not match:
            raise ValueError('Unsupported inline photo')
        body = base64.b64decode(match[2], validate=True)
        if len(body) > MAX_BYTES:
            raise ValueError('Photo exceeds size bound')
        return body
    opener = urllib.request.build_opener(PublicRedirects())
    url = source_url(source)
    for attempt in range(3):
        try:
            with opener.open(urllib.request.Request(url, headers={'User-Agent': 'WayYaam-photo-backfill/1'}), timeout=25) as response:
                body = response.read(MAX_BYTES + 1)
                if len(body) > MAX_BYTES:
                    raise ValueError('Photo exceeds size bound')
                return body
        except (urllib.error.URLError, TimeoutError):
            if attempt == 2:
                raise
            time.sleep(1)


def variants(body):
    from PIL import Image, ImageOps
    with Image.open(io.BytesIO(body)) as image:
        extension = {'JPEG': 'jpg', 'PNG': 'png', 'WEBP': 'webp', 'AVIF': 'avif'}.get(image.format)
        if not extension or getattr(image, 'is_animated', False):
            return None
        preview = ImageOps.exif_transpose(image)
        preview.thumbnail((400, 400), Image.Resampling.LANCZOS)
        preview = preview.convert('RGBA' if 'A' in preview.getbands() else 'RGB')
        output = io.BytesIO()
        for quality in (72, 60, 48):
            output = io.BytesIO()
            preview.save(output, format='WEBP', quality=quality, method=6)
            if output.tell() <= 45 * 1024:
                break
        if output.tell() >= len(body):
            return None
        encoded = output.getvalue()
        # Decode generated bytes before they can enter the upload plan.
        with Image.open(io.BytesIO(encoded)) as check:
            check.load()
            if check.format != 'WEBP' or max(check.size) > 400:
                raise ValueError('Invalid preview')
        return extension, encoded, preview.size


def updates(snapshot, plans):
    mapping = {(p['catalog_id'], p['source']): p['target'] for p in plans}
    result = []
    for table in ('product_images', 'product'):
        for row in snapshot[table]:
            catalog = row['catalog_id'] if table == 'product_images' else legacy_id(snapshot)
            fields = ('url',) if table == 'product_images' else ('image_url', 'image_urls')
            before, after = {}, {}
            for field in fields:
                value = row.get(field)
                mapped = [mapping.get((catalog, v), v) for v in value] if isinstance(value, list) else mapping.get((catalog, value), value)
                if mapped != value:
                    before[field], after[field] = value, mapped
            if after:
                result.append({'table': table, 'id': row['id'], 'before': before, 'after': after})
    return result


def literal(value):
    return "'" + str(value).replace("'", "''") + "'"


def transaction(changes):
    tag = '$backfill_' + hashlib.sha256(json.dumps(changes, sort_keys=True).encode()).hexdigest() + '$'
    statements = ['BEGIN;', "SET LOCAL lock_timeout='5s';", "SET LOCAL statement_timeout='60s';", f'DO {tag} DECLARE changed integer; BEGIN']
    for change in changes:
        table = change['table']
        allowed = {'product_images': {'url'}, 'product': {'image_url', 'image_urls'}}
        fields = set(change['after'])
        if table not in allowed or not fields or not fields <= allowed[table] or fields != set(change['before']):
            raise ValueError('Update outside product photo scope')
        assignments, predicates = [], [f'id::text={literal(change["id"])}']
        for field in sorted(fields):
            def record(value):
                return f'(json_populate_record(null::public.{table}, {literal(json.dumps({field: value}))}))."{field}"'
            assignments.append(f'"{field}"={record(change["after"][field])}')
            predicates.append(f'"{field}" IS NOT DISTINCT FROM {record(change["before"][field])}')
        statements.extend([f'UPDATE public.{table} SET {", ".join(assignments)} WHERE {" AND ".join(predicates)};', 'GET DIAGNOSTICS changed = ROW_COUNT;', "IF changed <> 1 THEN RAISE EXCEPTION 'Concurrent photo edit; entire batch rolled back'; END IF;"])
    return '\n'.join(statements + [f'END; {tag};', 'COMMIT;'])


def prepare(snapshot, root):
    (root / 'files').mkdir(parents=True, exist_ok=True)
    cache, plans, skipped, failures = {}, [], [], []
    previous = root / 'plan.json'
    if previous.exists():
        for item in json.loads(previous.read_text())['plans']:
            full = (root / 'files' / item['full']).read_bytes()
            if hashlib.sha256(full).hexdigest() != item['full_sha256']:
                raise ValueError('Previously prepared full image changed')
            if item['source'] not in cache:
                cache[item['source']] = (full, variants(full))
    for index, ((catalog, source), count) in enumerate(references(snapshot).items(), 1):
        if has_preview(source):
            skipped.append({'catalog_id': catalog, 'source': source, 'reason': 'already_versioned'})
            continue
        try:
            if source not in cache:
                body = download(source)
                cache[source] = (body, variants(body))
            body, generated = cache[source]
            if generated is None:
                skipped.append({'catalog_id': catalog, 'source': source, 'reason': 'animated_or_already_small'})
                continue
            extension, preview, dimensions = generated
            digest = hashlib.sha256(body).hexdigest()
            full_name, thumb_name = f'{digest}.full-v1.{extension}', f'{digest}.thumb-v1.webp'
            (root / 'files' / full_name).write_bytes(body)
            (root / 'files' / thumb_name).write_bytes(preview)
            plans.append({'catalog_id': catalog, 'source': source, 'target': PUBLIC + f'{catalog}/media/{full_name}', 'full': full_name, 'thumb': thumb_name, 'full_sha256': digest, 'thumb_sha256': hashlib.sha256(preview).hexdigest(), 'full_bytes': len(body), 'thumb_bytes': len(preview), 'dimensions': dimensions, 'references': count})
        except Exception as error:
            # Keep the original reference; never substitute a broken/unknown image.
            failures.append({'catalog_id': catalog, 'source': source, 'error': type(error).__name__, 'detail': str(error)})
        if index % 20 == 0:
            print(json.dumps({'processed': index, 'plans': len(plans), 'failed': len(failures)}), flush=True)
    changes = updates(snapshot, plans)
    result = {'plans': plans, 'changes': changes, 'skipped': skipped, 'failures': failures}
    (root / 'plan.json').write_text(json.dumps(result, ensure_ascii=False, indent=2))
    (root / 'apply.sql').write_text(transaction(changes))
    reversed_changes = [{**c, 'before': c['after'], 'after': c['before']} for c in reversed(changes)]
    (root / 'rollback.sql').write_text(transaction(reversed_changes))
    print(json.dumps({'variants': len(plans), 'rows': len(changes), 'skipped': len(skipped), 'failures': len(failures)}), flush=True)


def apply(root):
    plan = json.loads((root / 'plan.json').read_text())
    env = json.loads(subprocess.check_output(['docker', 'inspect', 'supabase-storage']))[0]['Config']['Env']
    key = next(v.split('=', 1)[1] for v in env if v.startswith('SERVICE_KEY='))
    seen = set()
    for index, item in enumerate(plan['plans'], 1):
        for kind in ('thumb', 'full'):
            name = item[kind]
            if Path(name).name != name or not re.fullmatch(r'[a-f0-9]{64}\.(full-v1\.(jpg|png|webp|avif)|thumb-v1\.webp)', name):
                raise ValueError('Invalid planned filename')
            storage_path = f'{item["catalog_id"]}/media/{name}'
            if storage_path in seen:
                continue
            body = (root / 'files' / name).read_bytes()
            expected = item[f'{kind}_sha256']
            if hashlib.sha256(body).hexdigest() != expected:
                raise ValueError('Staged content hash mismatch')
            url = PUBLIC + storage_path
            try:
                with urllib.request.urlopen(url, timeout=30) as response:
                    existing = response.read(MAX_BYTES + 1)
                if hashlib.sha256(existing).hexdigest() != expected:
                    raise ValueError('Existing immutable object differs; not overwritten')
            except urllib.error.HTTPError as error:
                if error.code not in (400, 404):
                    raise
                mime = {'jpg': 'image/jpeg', 'png': 'image/png', 'webp': 'image/webp', 'avif': 'image/avif'}[name.rsplit('.', 1)[-1]]
                request = urllib.request.Request('https://api.wayyaam.ru/storage/v1/object/catalog-assets/' + storage_path, data=body, method='POST', headers={'Authorization': 'Bearer ' + key, 'apikey': key, 'Content-Type': mime, 'x-upsert': 'false', 'cache-control': 'max-age=31536000'})
                with urllib.request.urlopen(request, timeout=30) as response:
                    response.read()
            with urllib.request.urlopen(url, timeout=30) as response:
                if hashlib.sha256(response.read(MAX_BYTES + 1)).hexdigest() != expected:
                    raise ValueError('Public verification failed; database unchanged')
            seen.add(storage_path)
        if index % 20 == 0:
            print(json.dumps({'verified_pairs': index}), flush=True)
    # Generate again from validated JSON; never execute a copied SQL file blindly.
    result = subprocess.run(['docker', 'exec', '-i', 'supabase-db', 'psql', '-X', '-v', 'ON_ERROR_STOP=1', '-U', 'postgres', '-d', 'postgres'], input=transaction(plan['changes']), text=True, capture_output=True, check=True)
    print(json.dumps({'verified_files': len(seen), 'updated_rows': len(plan['changes']), 'transaction': result.stdout.strip()}), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--snapshot', type=Path)
    parser.add_argument('--directory', type=Path, required=True)
    parser.add_argument('--apply', action='store_true')
    args = parser.parse_args()
    if args.apply:
        apply(args.directory)
    else:
        if not args.snapshot:
            parser.error('--snapshot required for prepare')
        prepare(json.loads(args.snapshot.read_text()), args.directory)


if __name__ == '__main__':
    main()
